"""Export ParkSmart data from MySQL into the website's data.js.

The website (index.html + script.js) reads two JavaScript constants from
data.js: PARKSMART_HOURLY and PARKSMART_GARAGES. This script rebuilds that
file from the parking_tracker database, so the site shows real historical
data instead of demo values. No web server is needed.

Requires: schema.sql, the UCI data, schema_v2_special_cases.sql,
sample_data.sql and website_views.sql loaded in MySQL.

Usage:
    python export_data_js.py              # writes ./data.js
    python export_data_js.py path/to/data.js

Connection settings come from environment variables (same names as
import_data.py): MYSQL_HOST, MYSQL_PORT, MYSQL_USER, MYSQL_PASSWORD,
MYSQL_DATABASE. Anything not set is asked for or defaulted. No password is
ever written to a file.
"""
import json
import os
import sys
from datetime import datetime
from getpass import getpass

import mysql.connector


def connect():
    user = os.getenv('MYSQL_USER') or input('MySQL user [root]: ').strip() or 'root'
    password = os.getenv('MYSQL_PASSWORD')
    if password is None:
        password = getpass(f'MySQL password for {user}: ')
    return mysql.connector.connect(
        host=os.getenv('MYSQL_HOST', 'localhost'),
        port=int(os.getenv('MYSQL_PORT', '3306')),
        user=user,
        password=password,
        database=os.getenv('MYSQL_DATABASE', 'parking_tracker'),
    )


def fetch(cursor, sql):
    cursor.execute(sql)
    return cursor.fetchall()


def build(conn):
    cur = conn.cursor(dictionary=True)

    overall = fetch(cur, """
        SELECT hour_of_day AS hour, avg_available_pct AS available
        FROM v_overall_hourly ORDER BY hour_of_day""")
    hourly = [{'hour': int(r['hour']), 'available': float(r['available'])} for r in overall]
    overall_by_hour = {h['hour']: h['available'] for h in hourly}
    if 14 not in overall_by_hour:
        raise SystemExit('No data for 14:00; the website needs that hour as its baseline.')

    per_lot = {}
    for r in fetch(cur, "SELECT lot_id, hour_of_day, avg_available_pct FROM v_lot_hourly"):
        per_lot.setdefault(r['lot_id'], {})[int(r['hour_of_day'])] = float(r['avg_available_pct'])

    profiles = fetch(cur, """
        SELECT lot_id, lot_code, display_name, area, capacity, parking_type, payment
        FROM v_lot_profile
        WHERE is_total = 0
        ORDER BY display_name""")

    garages = []
    for p in profiles:
        lot_hours = per_lot.get(p['lot_id'], {})
        at14 = lot_hours.get(14, overall_by_hour[14])
        garages.append({
            'id': f"LOT-{p['lot_id']}",
            'name': p['display_name'],
            'code': p['lot_code'],
            'capacity': int(p['capacity']),
            'availabilityAt14': round(at14),
            'area': p['area'] or 'Birmingham',
            'parkingType': p['parking_type'],
            'payment': p['payment'],
            # Extra field: real per-hour availability for this lot.
            # script.js can use it instead of the 14:00-based estimate.
            'hourly': {str(h): v for h, v in sorted(lot_hours.items())},
        })

    cur.close()
    return hourly, garages


def write_js(path, hourly, garages):
    stamp = datetime.now().strftime('%Y-%m-%d %H:%M')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by export_data_js.py from the parking_tracker MySQL database\n')
        f.write(f'// on {stamp}. Do not edit by hand; re-run the script instead.\n')
        f.write('// Occupancy: UCI Parking Birmingham (Oct-Dec 2016), quality_flag = OK only.\n')
        f.write('// Parking type and payment come from SAMPLE rules in sample_data.sql.\n')
        f.write('const PARKSMART_HOURLY = ')
        f.write(json.dumps(hourly, indent=2))
        f.write(';\n\nconst PARKSMART_GARAGES = ')
        f.write(json.dumps(garages, indent=2))
        f.write(';\n')


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'data.js'
    try:
        conn = connect()
    except mysql.connector.Error as exc:
        raise SystemExit(f'Could not connect to MySQL: {exc}')
    try:
        hourly, garages = build(conn)
    finally:
        conn.close()
    write_js(out, hourly, garages)
    print(f'Wrote {out}: {len(hourly)} hours, {len(garages)} lots')


if __name__ == '__main__':
    main()
